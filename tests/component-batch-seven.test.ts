test('ordinary list actions stay independent and disabled rows block their controls and link', async () => {
  setReducedMotion(true)
  const wrapper = mount(ListActionsDemo, { attachTo: document.body })
  const primary = button(wrapper, 'Project details')
  const save = wrapper.get('input[aria-label="Save project"]')
  const more = wrapper.get('button[aria-label="More project actions"]')
  expect(primary.find('input').exists()).toBe(false)
  expect(primary.find('button').exists()).toBe(false)
  await save.setValue(true)
  await more.trigger('click')
  expect(wrapper.get('[role="status"]').text()).toBe('Project opens: 0 · Saved: true · Sync: true · More: 1')
  await primary.trigger('click')
  await wrapper.get('input[aria-label="Enable background sync"]').setValue(false)
  expect(wrapper.get('[role="status"]').text()).toBe('Project opens: 1 · Saved: true · Sync: false · More: 1')
  const link = wrapper.get('a')
  const destination = link.attributes('href')
  await wrapper.findAll('input[type="checkbox"]')[0]!.setValue(true)
  expect(save.attributes('disabled')).toBeDefined()
  expect(more.attributes('disabled')).toBeDefined()
  expect(link.attributes('href')).toBeUndefined()
  expect(link.attributes('aria-disabled')).toBe('true')
  expect(link.attributes('tabindex')).toBe('-1')
  await primary.trigger('click')
  await more.trigger('click')
  expect(wrapper.get('[role="status"]').text()).toContain('Project opens: 1')
  expect(wrapper.get('[role="status"]').text()).toContain('More: 1')
  const click = new MouseEvent('click', { bubbles: true, cancelable: true })
  link.element.dispatchEvent(click)
  expect(click.defaultPrevented).toBe(true)
  await wrapper.findAll('input[type="checkbox"]')[0]!.setValue(false)
  expect(link.attributes('href')).toBe(destination)
})

test('grouped list preserves selection across keyed reordering and navigates the new DOM order', async () => {
  setReducedMotion(true)
  const wrapper = mount(ListGroupsDemo, { attachTo: document.body })
  await flushPromises()
  await button(wrapper, 'Focus selected row').trigger('click')
  const research = option(wrapper, 'research')
  expect(document.activeElement).toBe(research.element)
  await button(wrapper, 'Reverse project order').trigger('click')
  await flushPromises()
  expect(wrapper.findAll('[role="option"]').map(row => row.text())).toEqual(['Inbox', 'Archive', 'release', 'prototype', 'research'])
  expect(option(wrapper, 'research').element).toBe(research.element)
  expect(research.attributes('aria-selected')).toBe('true')
  await research.trigger('keydown', { key: 'ArrowDown' })
  expect(document.activeElement).toBe(option(wrapper, 'Inbox').element)
  expect(research.attributes('aria-selected')).toBe('true')
  expect(wrapper.findAll('li[role="presentation"]').filter(row => row.text() === 'Projects')).toHaveLength(1)
  await wrapper.get('input[type="checkbox"]').setValue(false)
  expect(wrapper.findAll('li').some(row => row.text() === 'Projects')).toBe(false)
})

