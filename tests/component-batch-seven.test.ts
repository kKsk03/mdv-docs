test('loading task owns busy state and announces failure and successful retry outside its region', async () => {
  setReducedMotion(true)
  vi.useFakeTimers({ toFake: ['setTimeout', 'clearTimeout'] })
  const wrapper = mount(LoadingTaskDemo)
  const region = wrapper.get('section')
  await wrapper.get('input[type="checkbox"]').setValue(true)
  await button(wrapper, 'Load recommendations').trigger('click')
  expect(region.attributes('aria-busy')).toBe('true')
  expect(region.get('[role="progressbar"]').attributes('aria-label')).toBe('Loading recommendations')
  expect(region.get('[role="progressbar"]').attributes('aria-valuenow')).toBeUndefined()
  expect(button(wrapper, 'Load recommendations').attributes('disabled')).toBeDefined()
  expect(region.find('[role="status"]').exists()).toBe(false)
  await vi.advanceTimersByTimeAsync(1200)
  expect(region.attributes('aria-busy')).toBe('false')
  expect(region.find('[role="progressbar"]').exists()).toBe(false)
  expect(wrapper.get('[role="status"]').text()).toContain('Loading failed.')
  await wrapper.get('input[type="checkbox"]').setValue(false)
  await button(wrapper, 'Load recommendations').trigger('click')
  await vi.advanceTimersByTimeAsync(1200)
  expect(region.text()).toContain('Your reading list')
  expect(wrapper.get('[role="status"]').text()).toBe('Recommendations are ready.')
})

test('decorative button indicator leaves naming to its disabled busy owner and reports completion', async () => {
  setReducedMotion(true)
  vi.useFakeTimers({ toFake: ['setTimeout', 'clearTimeout'] })
  const wrapper = mount(LoadingButtonDemo)
  await button(wrapper, 'Save draft').trigger('click')
  const owner = button(wrapper, 'Saving draft')
  expect(owner.attributes('aria-busy')).toBe('true')
  expect(owner.attributes('disabled')).toBeDefined()
  const indicator = owner.get('.mdv-loading-indicator')
  expect(indicator.attributes('aria-hidden')).toBe('true')
  expect(indicator.attributes('role')).toBeUndefined()
  expect(indicator.attributes('aria-label')).toBeUndefined()
  await owner.trigger('click')
  await vi.advanceTimersByTimeAsync(900)
  expect(button(wrapper, 'Save draft').attributes('disabled')).toBeUndefined()
  expect(wrapper.get('[role="status"]').text()).toBe('Saved 1 times.')
})

