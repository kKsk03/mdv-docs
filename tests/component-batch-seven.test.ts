function button(wrapper: Pick<DOMWrapper<Element>, 'findAll'>, text: string) {
  const target = wrapper.findAll('button').find(candidate => candidate.text().startsWith(text))
  if (!target) throw new Error(`Missing button: ${text}`)
  return target
}

function option(wrapper: Pick<DOMWrapper<Element>, 'findAll'>, text: string) {
  const target = wrapper.findAll('[role="option"]').find(candidate => candidate.text() === text)
  if (!target) throw new Error(`Missing option: ${text}`)
  return target
}

test('linear task reports unknown and measured progress, completion, failure, and retry', async () => {
  setReducedMotion(true)
  const wrapper = mount(LinearProgressTaskDemo)
  expect(wrapper.find('[role="progressbar"]').exists()).toBe(false)
  await button(wrapper, 'Start upload').trigger('click')
  const region = wrapper.get('section')
  let progress = wrapper.get('[role="progressbar"]')
  expect(region.attributes('aria-busy')).toBe('true')
  expect(progress.attributes('aria-valuenow')).toBeUndefined()
  expect(progress.attributes('aria-valuetext')).toBeUndefined()
  expect(button(wrapper, 'Upload 64 MB').attributes('disabled')).toBeDefined()
  await button(wrapper, 'Progress is known').trigger('click')
  progress = wrapper.get('[role="progressbar"]')
  expect(progress.attributes('aria-valuemax')).toBe('256')
  expect(progress.attributes('aria-valuenow')).toBe('0')
  for (let index = 0; index < 4; index++) await button(wrapper, 'Upload 64 MB').trigger('click')
  expect(progress.attributes('aria-valuenow')).toBe('256')
  expect(progress.attributes('aria-valuetext')).toBe('256 of 256 MB')
  expect(region.attributes('aria-busy')).toBe('false')
  expect(wrapper.get('[role="status"]').text()).toContain('Report uploaded.')
  expect(region.find('[role="status"]').exists()).toBe(false)
  await button(wrapper, 'Start upload').trigger('click')
  await button(wrapper, 'Simulate failure').trigger('click')
  expect(wrapper.find('[role="progressbar"]').exists()).toBe(false)
  expect(region.attributes('aria-busy')).toBe('false')
  expect(wrapper.get('[role="status"]').text()).toContain('Upload failed.')
  await button(wrapper, 'Start upload').trigger('click')
  expect(wrapper.get('[role="progressbar"]').attributes('aria-valuenow')).toBeUndefined()
})

test('list options keep strict value types and separate focus movement from selection', async () => {
  setReducedMotion(true)
  const wrapper = mount(ListSelectionDemo, { attachTo: document.body })
  await flushPromises()
  const single = wrapper.get('[role="listbox"][aria-label="Account preference"]')
  const profile = option(single, 'Profile')
  expect(profile.attributes('tabindex')).toBe('0')
  ;(profile.element as HTMLElement).focus()
  await profile.trigger('keydown', { key: 'ArrowDown' })
  const numeric = option(single, 'Numeric value 1')
  expect(document.activeElement).toBe(numeric.element)
  expect(profile.attributes('aria-selected')).toBe('true')
  await numeric.trigger('keydown', { key: ' ' })
  expect(numeric.attributes('aria-selected')).toBe('true')
  expect(wrapper.findAll('[role="status"]')[0]!.text()).toBe('Single: number 1')
  const text = option(single, 'Text value 1')
  await text.trigger('click')
  await text.trigger('click')
  expect(text.attributes('aria-selected')).toBe('true')
  expect(numeric.attributes('aria-selected')).toBe('false')
  expect(wrapper.findAll('[role="status"]')[0]!.text()).toBe('Single: string "1"')
  await option(single, 'Unavailable setting').trigger('click')
  expect(text.attributes('aria-selected')).toBe('true')
  const multiple = wrapper.get('[role="listbox"][aria-label="Notification categories"]')
  expect(multiple.attributes('aria-multiselectable')).toBe('true')
  await option(multiple, 'Product updates').trigger('click')
  await option(multiple, 'Security alerts').trigger('click')
  expect(wrapper.findAll('[role="status"]')[1]!.text()).toBe('Multiple: ["security"]')
  expect(wrapper.findAll('[role="listbox"] input')).toHaveLength(0)
})

